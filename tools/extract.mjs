import fs from 'node:fs';
import path from 'node:path';
import { loadScratchpiler, fakeMonaco, toolsDir } from './js-bundle.mjs';

const sp = await loadScratchpiler();
sp.language.registerLanguage(fakeMonaco());

const rs = value => {
    if (value === undefined || value === null) return 'None';
    return '"' + String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '\\r').replace(/\t/g, '\\t') + '"';
};
const opt = value => value === undefined || value === null ? 'None' : `Some(${rs(value)})`;
const strList = list => `&[${list.map(rs).join(', ')}]`;

const sigEntry = sig => `Sig { label: ${rs(sig.label)}, params: &[${sig.params.map(p => `(${rs(p.label)}, ${rs(p.documentation ?? '')})`).join(', ')}] }`;

const staticItems = sp.language.withCompletionBehavior(sp.language.buildSuggestions(fakeMonaco(), 'range', 'hat'));
const commandName = command => command ? rs(command.id) : '""';

const out = [];
out.push('// Generated by tools/extract.mjs from the Scratchpiler sources. Do not edit.');
out.push('#![allow(clippy::all)]');
out.push('use crate::data::{Sig, StaticItem, AsmParam};');
out.push(`pub static KEYWORDS: &[&str] = ${strList(sp.constants.KEYWORDS)};`);
out.push(`pub static CALL_SIGS: &[(&str, &str)] = &[${Object.entries(sp.compiler.CALL_SIGS).map(([k, v]) => `(${rs(k)}, ${rs(v)})`).join(', ')}];`);
out.push(`pub static SIG_DB: &[(&str, Sig)] = &[${Object.entries(globalThis.__SIG_DB).map(([k, v]) => `(${rs(k)}, ${sigEntry(v)})`).join(',\n')}];`);
out.push(`pub static PEN_DOT_SIG: &[(&str, Sig)] = &[${Object.entries(globalThis.__PEN_DOT_SIG).map(([k, v]) => `(${rs(k)}, ${sigEntry(v)})`).join(',\n')}];`);
out.push(`pub static MODIFIER_DOCS: &[(&str, &str, &str)] = &[${Object.entries(sp.language.MODIFIER_DOCS).map(([k, v]) => `(${rs(k)}, ${rs(v.detail)}, ${rs(v.documentation)})`).join(', ')}];`);
out.push(`pub static KEY_NAMES: &[&str] = ${strList(sp.language.KEY_NAMES)};`);
out.push(`pub static ASM_OPCODES: &[(&str, &[AsmParam])] = &[${Object.entries(sp.asm.ASM_OPCODES).map(([op, schema]) =>
    `(${rs(op)}, &[${schema.params.map(p => `AsmParam { name: ${rs(p.name)}, kind: ${rs(p.kind)}, value_type: ${rs(p.valueType)} }`).join(', ')}])`).join(',\n')}];`);
out.push(`pub static STATIC_ITEMS: &[StaticItem] = &[${staticItems.map(item => `StaticItem { label: ${rs(item.label)}, kind: ${rs(item.kind)}, detail: ${rs(item.detail ?? '')}, insert_text: ${rs(item.insertText)}, documentation: ${opt(item.documentation?.value)}, hat_range: ${item.range === 'hat'}, filter_text: ${opt(item.filterText)}, command: ${commandName(item.command)}, snippet: ${item.insertTextRules === 4} }`).join(',\n')}];`);

const target = path.join(toolsDir, '..', 'src', 'data', 'generated.rs');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out.join('\n') + '\n');
console.log(`wrote ${target}: ${staticItems.length} completion items, ${Object.keys(globalThis.__SIG_DB).length} signatures`);
